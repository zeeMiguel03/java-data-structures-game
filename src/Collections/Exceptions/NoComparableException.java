public class NoComparableException extends RuntimeException {

    /**
     * Creates an NoComparableException
     */
    public NoComparableException() {
        super();
    }

    /**
     * Creates an NoComparableException
     *
     * @param message the message
     */
    public NoComparableException(String message) {
        super(message);
    }  
}
